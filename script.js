/* STATS */

function updateStatsPage() {

    const stats =
        getStats();


    document.getElementById(
        "totalChallenges"
    ).textContent =
        stats.totalChallenges;


    document.getElementById(
        "currentStreak"
    ).textContent =
        stats.currentStreak;


    document.getElementById(
        "longestStreak"
    ).textContent =
        stats.longestStreak;


    document.getElementById(
        "totalMinutes"
    ).textContent =
        stats.totalMinutes;


    const activity =
        document.getElementById(
            "activityMessage"
        );


    if (stats.totalChallenges === 0) {

        activity.textContent =
            "Complete your first challenge to start building your history.";

    } else {

        activity.textContent =
            `You've completed ${stats.totalChallenges} challenge${stats.totalChallenges === 1 ? "" : "s"} and reclaimed ${stats.totalMinutes} minutes.`;

    }

}


