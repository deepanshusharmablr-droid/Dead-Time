function startChallenge() {

    if (!currentChallenge) {
        return;
    }


    currentStep = 0;


    const minutes =
        selectedTime || 10;


    remainingSeconds =
        minutes * 60;


    isPaused = false;


    challengeIntro.style.display =
        "none";

    completionScreen.classList.remove(
        "visible"
    );

    challengeWorkspace.classList.add(
        "visible"
    );


    workspaceCategory.textContent =
        currentChallenge.category;

    workspaceTitle.textContent =
        currentChallenge.title;


    pauseButton.textContent =
        "PAUSE";


    updateTimer();

    renderStep();


    clearInterval(timerInterval);


    timerInterval =
        setInterval(() => {

            if (!isPaused) {

                remainingSeconds--;

                updateTimer();

                if (remainingSeconds <= 0) {

                    clearInterval(timerInterval);

                    timer.textContent =
                        "00:00";

                    pauseButton.textContent =
                        "TIME'S UP";

                    pauseButton.disabled =
                        true;

                }

            }

        }, 1000);

}


/* RENDER STEP */

function renderStep() {

    const step =
        currentChallenge.steps[currentStep];


    const totalSteps =
        currentChallenge.steps.length;


    const stepNumber =
        currentStep + 1;


    const percentage =
        Math.round(
            (stepNumber / totalSteps) * 100
        );


    stepCounter.textContent =
        `STEP ${stepNumber} / ${totalSteps}`;


    progressPercent.textContent =
        `${percentage}%`;


    progressFill.style.width =
        `${percentage}%`;


    stepLabel.textContent =
        `STEP ${stepNumber}`;


    stepTitle.textContent =
        step.title;


    stepContent.textContent =
        step.content;


    stepExample.textContent =
        step.example;


    if (currentStep === totalSteps - 1) {

        nextButton.textContent =
            "FINISH CHALLENGE ✓";

    } else {

        nextButton.textContent =
            "NEXT STEP →";

    }

}


/* NEXT STEP */

nextButton.addEventListener(
    "click",
    () => {

        if (!currentChallenge) {
            return;
        }


        if (
            currentStep >=
            currentChallenge.steps.length - 1
        ) {

            completeChallenge();

            return;

        }


        currentStep++;

        renderStep();

    }
);


/* PAUSE */

pauseButton.addEventListener(
    "click",
    () => {

        if (remainingSeconds <= 0) {
            return;
        }


        isPaused =
            !isPaused;


        pauseButton.textContent =
            isPaused
                ? "RESUME"
                : "PAUSE";

    }
);


/* TIMER */

function updateTimer() {

    const minutes =
        Math.floor(
            remainingSeconds / 60
        );

    const seconds =
        remainingSeconds % 60;


    timer.textContent =
        `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;

}


/* COMPLETE */

function completeChallenge() {

    clearInterval(timerInterval);


    const stats =
        getStats();


    const minutes =
        selectedTime || 10;


    stats.totalChallenges++;

    stats.totalMinutes += minutes;


    const today =
        new Date()
            .toISOString()
            .split("T")[0];


    stats.completions.push({

        date: today,

        minutes: minutes,

        title: currentChallenge.title

    });


    calculateStreak(stats);

    saveStats(stats);


    challengeWorkspace.classList.remove(
        "visible"
    );


    completionScreen.classList.add(
        "visible"
    );


    completionMessage.textContent =
        `${minutes} minutes reclaimed. That's time you didn't waste.`;


    updateStatsPage();

}


/* STREAK */

function calculateStreak(stats) {

    const dates =
        [...new Set(
            stats.completions.map(
                item => item.date
            )
        )].sort().reverse();


    if (dates.length === 0) {

        stats.currentStreak = 0;

        return;

    }


    let streak = 1;


    for (
        let i = 0;
        i < dates.length - 1;
        i++
    ) {

        const current =
            new Date(dates[i]);

        const previous =
            new Date(dates[i + 1]);


        const difference =
            (current - previous) /
            (1000 * 60 * 60 * 24);


        if (difference === 1) {

            streak++;

        } else {

            break;

        }

    }


    const today =
        new Date()
            .toISOString()
            .split("T")[0];


    const lastDate =
        dates[0];


    const daysSinceLast =
        (
            new Date(today) -
            new Date(lastDate)
        ) /
        (1000 * 60 * 60 * 24);


    if (daysSinceLast > 1) {
        streak = 0;
    }


    stats.currentStreak =
        streak;


    if (
        streak >
        stats.longestStreak
    ) {

        stats.longestStreak =
            streak;

    }

}


