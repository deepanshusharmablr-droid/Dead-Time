/* STORAGE */

function getStats() {

    const saved =
        localStorage.getItem("deadTimeStats");

    if (!saved) {

        return {
            totalChallenges: 0,
            totalMinutes: 0,
            completions: [],
            currentStreak: 0,
            longestStreak: 0
        };

    }

    return JSON.parse(saved);
}


function saveStats(stats) {

    localStorage.setItem(
        "deadTimeStats",
        JSON.stringify(stats)
    );

}


